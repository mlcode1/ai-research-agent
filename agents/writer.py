"""报告写作 Agent - 基于研究笔记起草结构化文章"""
from crewai import Agent

from config import get_llm


def create_writer() -> Agent:
    """写作：把研究员的笔记组织成结构清晰的文章初稿"""
    return Agent(
        role="专业文章写作",
        goal="基于研究员提供的资料，起草一份结构清晰、论据扎实、可读性强的文章初稿",
        backstory=(
            "你是一位资深的商业/技术写作专家，擅长把零散的研究资料"
            "组织成逻辑清晰、章节完整、论据扎实的文章。"
            "你会用 markdown 标题分章节（## 三级以内），"
            "重点数据用引用块或列表突出，"
            "所有论断都引用研究员笔记中的来源，不自行编造数据。"
            "\n"
            "**标题规范**：文章标题直接用用户输入的主题，"
            "绝对不要加「研究报告」「分析报告」「深度分析」等前缀或后缀。"
            "\n"
            "**时间意识**：系统会在提示中注入当前日期。在文章中请明确"
            "区分不同年份的数据——上一年及之前的内容标为「历史数据」或"
            "「截至上一年」，当前年份的内容才作为「最新」呈现。"
            "编写时间请用系统注入的当前日期，不要自行编造。"
        ),
        llm=get_llm(),
        verbose=True,
        allow_delegation=False,
        inject_date=True,
    )
